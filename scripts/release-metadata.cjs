'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const {version}=JSON.parse(read('package.json'));
assert.match(version,/^\d+\.\d+\.\d+$/);
require(path.join(root,'public/assets/ayflux-version.js'));
const app=globalThis.AyFluxVersion;
assert.equal(app.version,version);
assert.equal(JSON.parse(read('package-lock.json')).version,version);
assert.equal(JSON.parse(read('package-lock.json')).packages[''].version,version);
assert.equal(read('CITATION.cff'),read('public/CITATION.cff'));
assert.ok(read('CITATION.cff').includes('version: "'+version+'"'));
assert.ok(read('CITATION.cff').includes('date-released: "'+app.releaseDate+'"'));
const header='## ['+version+'] - '+app.releaseDate,log=read('CHANGELOG.md');
const start=log.indexOf(header);assert.ok(start>=0,'Changelog must identify the version and release date');
const end=log.indexOf('\n## [',start+header.length);
const notes=log.slice(start,end<0?undefined:end).trim()+'\n';
if(process.argv[2])fs.writeFileSync(process.argv[2],notes);
console.log(JSON.stringify({version,tag:'v'+version,date:app.releaseDate}));
